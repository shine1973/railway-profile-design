test('导出当前坐标范围、序号刻度、负设计高程偏移和标注，与软件共用规则',async()=>{
  const p=newProject(Array.from({length:30},(_,i)=>({id:`p${i}`,sourceRow:i+2,no:i%3,feature:`特征<&${i}`,fore:500+i*3,back:null})));
  p.controls={p4:-200,p24:0};p.segments=[['p4','p24']];
  const options={view:{min:4.5,max:20.5},plotWidth:480,labelNo:true,labelFeature:true,labelLift:true};
  const rows=calculate(p),model=chartModel(rows,p.controls,options),buffer=await exportWorkbook(p,options);
  const zip=await JSZip.loadAsync(buffer),chart=await zip.file('xl/charts/chart1.xml').async('string');
  assert.match(chart,/<a:t>记录序号<\/a:t>/);assert.doesNotMatch(chart,/累计距离/);
  assert.match(chart,/&apos;参数&apos;!\$B\$2:\$B\$31/);
  assert.match(chart,new RegExp(`<c:max val="${model.axis.max}"/><c:min val="${model.axis.min}"/>`));
  assert.match(chart,new RegExp(`<c:majorUnit val="${model.axis.step}"/>`));
  assert.match(chart,/<c:max val="20.5"\/><c:min val="4.5"\/>/);
  for(const tick of model.ticks)assert.ok(chart.includes(`<a:t>${tick}</a:t>`));
  assert.match(chart,/特征&lt;&amp;4/);assert.match(chart,/DF9E3D/);assert.match(chart,/D4374F/);
  const book=new ExcelJS.Workbook();await book.xlsx.load(buffer);
  const params=book.getWorksheet('参数'),data=book.getWorksheet('测量数据');
  assert.ok(model.offset>0);assert.equal(params.getCell('J2').value,model.offset);
  rows.forEach((r,i)=>{assert.equal(data.getCell(i+3,6).value,r.measured);assert.equal(params.getCell(i+2,6).result,r.measured+model.offset);});
  assert.equal(data.getCell('F3').alignment.horizontal,'center');
  const rels=await zip.file('xl/worksheets/_rels/sheet1.xml.rels').async('string');
  assert.match(rels,/rIdProfileChart/);assert.match(rels,/comments/);
  const noLabels=await JSZip.loadAsync(await exportWorkbook(p,{...options,labelNo:false,labelFeature:false,labelLift:false}));
  assert.doesNotMatch(await noLabels.file('xl/charts/chart1.xml').async('string'),/特征&lt;/);
});
test('填写模板：空白数据表、独立示例不误导入、填写转站后可直接导入',async()=>{
  const buffer=await exportTemplate();
  await assert.rejects(importWorkbook(buffer,'空模板'),/没有可导入的测点/);
  const book=new ExcelJS.Workbook();await book.xlsx.load(buffer);
  const s=book.getWorksheet('测量数据');
  assert.deepEqual(s.getRow(1).values.slice(1,12),['特征点','点号','前视读数','后视读数']);
  assert.ok(book.getWorksheet('填写说明'));
  for(let r=2;r<=s.rowCount;r++)for(let c=1;c<=4;c++)assert.equal(s.getCell(r,c).value,null);
  s.getRow(2).values=['起点',-2,1200,null];
  s.getRow(3).values=['转站点',-1,1250,800];
  s.getRow(4).values=['',0,830,null];
  const p=await importWorkbook(await book.xlsx.writeBuffer(),'填写模板');
  assert.equal(p.points.length,3);
  assert.deepEqual(p.points.map(p=>p.no),[-2,-1,0]);
  assert.deepEqual(calculate(p).map(p=>p.measured),[90,40,10]);
});
test('导出十一列、原始数据、负值样式、真实可编辑散点图与空段',async()=>{
  const p=newProject(parseRows([['特征点','点号','前视读数','后视读数'],['<岔心>',0,1200,null],['',0,1220,null],['',2,1240,null],['',3,1250,null]]));
  p.controls={p3:-5,p4:0};p.segments=[['p3','p4']];const buffer=await exportWorkbook(p);
  const book=new ExcelJS.Workbook();await book.xlsx.load(buffer);const s=book.getWorksheet('测量数据');
  assert.deepEqual(s.getRow(2).values.slice(1,12),['特征点','点号','前视读数','后视读数','仪器高','实测高程','设计高程','竖曲线半径（m）','坡度','递增量','起道量']);
  calculate(p).forEach((r,i)=>{assert.equal(s.getCell(i+3,5).value,r.instrument);assert.equal(s.getCell(i+3,6).value,r.measured);assert.ok(r.measured>=10);});
  assert.equal(s.autoFilter,undefined);assert.doesNotMatch(await (await JSZip.loadAsync(buffer)).file('xl/worksheets/sheet1.xml').async('string'),/<autoFilter/);
  assert.equal(s.getCell('G3').value,'未设计');assert.equal(s.getCell('K4').value,-5);assert.equal(s.getCell('K4').font.color.argb,'FFDC3545');assert.equal(s.getCell('I5').value,null);assert.equal(s.getCell('I4').numFmt,'0.0');assert.equal(s.getCell('A3').value,'<岔心>');
  const zip=await JSZip.loadAsync(buffer),chart=await zip.file('xl/charts/chart1.xml').async('string');
  assert.match(chart,/<c:scatterChart>/);assert.match(chart,/'测量数据'|&apos;测量数据&apos;/);assert.match(chart,/<c:dispBlanksAs val="gap"/);
  // WPS associates legend entries with physical series order: keep it aligned
  // with idx/order so hiding entry 3 cannot hide the control points instead.
  const seriesBlocks=[...chart.matchAll(/<c:ser>([\s\S]*?)<\/c:ser>/g)].map(m=>m[1]);
  assert.deepEqual(seriesBlocks.map(s=>Number(s.match(/<c:idx val="(\d+)"/)[1])),[0,1,2,3]);
  assert.match(seriesBlocks[3],/坐标网格（辅助）/);
  assert.match(chart,/<c:legendEntry><c:idx val="3"\/><c:delete val="1"\/><\/c:legendEntry>/);
  // Reserve separate vertical bands for plot/ticks, axis title and legend.
  const plotLayout=chart.match(/<c:plotArea><c:layout>([\s\S]*?)<\/c:layout>/)[1];
  assert.match(plotLayout,/<c:y val="0.16"\/>/);assert.match(plotLayout,/<c:h val="0.6"\/>/);
  const xAxis=chart.match(/<c:valAx><c:axId val="100"\/>[\s\S]*?<\/c:valAx>/)[0];
  assert.match(xAxis,/<c:y val="0.84"\/>/);
  const legend=chart.match(/<c:legend>[\s\S]*?<\/c:legend>/)[0];
  assert.match(legend,/<c:y val="0.92"\/>/);
  assert.match(chart,/\$F\$3:\$F\$6/);assert.match(chart,/\$O\$2:\$O\$5/);
  assert.match(await zip.file('xl/worksheets/sheet1.xml').async('string'),/<drawing r:id="rIdProfileChart"/);
  const imported=await importWorkbook(buffer,'test');assert.deepEqual(imported.points.map(p=>p.no),[0,0,2,3]);
});
